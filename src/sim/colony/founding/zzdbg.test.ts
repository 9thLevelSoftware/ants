import { it } from 'vitest';
import { SG } from '@/sim/colony/founding/sealGuide';
import { throatCase } from '@/sim/colony/founding/sealKit';
import { nestOf, pinTemperature, queen, stepUntil } from '@/sim/colony/founding/testkit';
import { floodCavity, floodStart, keyPos } from '@/sim/colony/founding/leak';
import { biteToward, inThroatOf } from '@/sim/colony/founding/seal';
import { cavityEntrances } from '@/sim/colony/founding/dig';
it('dbg', () => {
  const L: string[] = [];
  const c = throatCase({ pitchDeg: 55, widthBu: 2.1, soil: 'loam' });
  const sim = c.sim, bu = sim.world.bu, q = queen(sim), nest = nestOf(sim);
  pinTemperature(sim, 22);
  sim.enqueue({ type: 'cheat.fillSphere', pos: { x: c.mouth.x - 1.1 * bu, y: sim.field.height(c.mouth.x - 1.1 * bu, c.mouth.z), z: c.mouth.z }, r: 0.7 * bu, loose: true });
  const lip = { x: c.mouth.x - 2 * bu, y: sim.field.height(c.mouth.x - 2 * bu, c.mouth.z) + 0.5 * bu, z: c.mouth.z };
  sim.enqueue({ type: 'cheat.teleport', antId: q.id, pos: lip });
  sim.enqueue({ type: 'possess', antId: q.id });
  sim.tick();
  sim.enqueue({ type: 'action', actionId: 'seal-entrance', phase: 'start' });
  stepUntil(sim, () => (q.bb[SG.state] ?? 0) === 4, 50);
  const path = floodCavity(sim, floodStart(sim, nest)).path!;
  const way = keyPos(sim, path[path.length - 2], { x: 0, y: 0, z: 0 });
  L.push(`way ${(way.x - c.mouth.x) / bu} ${(way.y - c.mouth.y) / bu} ${(way.z - c.mouth.z) / bu}`);
  for (const e of cavityEntrances(sim, nest)) L.push(`ent ${e.id} throat ${inThroatOf(sim, q, e)}`);
  L.push(`action ${q.action?.id}`);
  L.push(`bite ${biteToward(sim, q, way)}`);
  throw new Error(L.join(' | '));
});
