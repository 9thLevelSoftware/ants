#!/usr/bin/env node
// After tools/audio/render.mjs: brings the audio records, public/assets/manifest.json and the audio rows of
// assets-src/MANIFEST.md in line with the files on disk. The prose of CREDITS.md files is written by hand.
//   node tools/audio/sync-records.mjs
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { SOUNDS } from './sounds/index.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const DATE = '2026-11-18';
const AUTHOR = 'FOUNDRESS project (original sound, rendered by code in this repository)';
const LICENCE = 'Original work of this project; no third-party recording, sample or preset is used';
const ORIGINAL_NOTE_SUFFIX = ' Original: generated by tools/audio, no input recordings.';
const KEPT_PROVENANCE = 'author page on OpenGameArt (CC0 badge as declared there); first-hand upload, not on the integrator list of second-hand files';

const source = {
  bed: (s) => `periodic by construction (noise filtered around the loop, events wrap), normalised to ${s.lufs} LUFS integrated on the decoded file`,
  loop: (s) => `periodic by construction, normalised to ${s.lufs} LUFS integrated on the decoded file`,
  oneShot: (s) => `35 Hz high-pass (${s.lowCutHz ?? 35} Hz here), fades, peak ${s.peakDb} dBFS, lowered where needed to keep the mean K-weighted loudness of the file it replaced`,
};

const recordsPath = path.join(ROOT, 'assets-src/records_audio.json');
const records = JSON.parse(fs.readFileSync(recordsPath, 'utf8'));
const specs = new Map(SOUNDS.map((s) => [s.id, s]));

const probe = (file) => Math.round(parseFloat(spawnSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', file], { encoding: 'utf8' }).stdout) * 100) / 100;

for (const r of records) {
  const spec = specs.get(r.id);
  const file = path.join(ROOT, r.path);
  if (spec) {
    if (!r.replaces) r.replaces = { title: r.title, author: r.author, source_page: r.source_page, license: r.license, removed: DATE };
    r.title = `FOUNDRESS original: ${spec.role}`;
    r.author = AUTHOR;
    r.source_page = `tools/audio/sounds (seed ${spec.seed}); rendered by tools/audio/render.mjs`;
    r.download_url = 'none (generated, no input recordings)';
    r.license = LICENCE;
    const kind = spec.oneShot ? 'oneShot' : r.subkind === 'ambience' ? 'bed' : 'loop';
    r.processing = `generated at 44.1 kHz, seed ${spec.seed}; ${source[kind](spec)}; ${spec.channels === 2 ? 'stereo' : 'mono'} 96 kbps MP3 (libmp3lame, bit-exact flags)`;
    r.note = `${spec.role}.${ORIGINAL_NOTE_SUFFIX}`;
    r.provenance = 'original';
    r.tier = 'A';
  } else {
    r.provenance = KEPT_PROVENANCE;
    r.tier = 'A';
  }
  r.bytes = fs.statSync(file).size;
  r.seconds = probe(file);
}
fs.writeFileSync(recordsPath, JSON.stringify(records, null, 1) + '\n');

// manifest.json (the pack manifest): audio entries only
const manPath = path.join(ROOT, 'public/assets/manifest.json');
const man = JSON.parse(fs.readFileSync(manPath, 'utf8'));
const byId = new Map(records.map((r) => [r.id, r]));
for (const a of man.assets) {
  const r = byId.get(a.id);
  if (!r || a.kind !== 'audio') continue;
  a.seconds = r.seconds; a.loop = r.loop; a.bytes = r.bytes;
  a.license = specs.has(a.id) ? 'original' : 'CC0-1.0';
  a.note = r.note;
}
man.total_bytes = man.assets.reduce((s, a) => s + a.bytes, 0);
man.notes = 'Paths are relative to the site root (public/). Textures and 9 audio files are CC0 / public-domain; the other 36 audio files are original work of this project (tools/audio); see assets-src/MANIFEST.md for sources. Normal maps are OpenGL (+Y up). Audio loop=true means the file is built to wrap seamlessly.';
fs.writeFileSync(manPath, JSON.stringify(man, null, 1));

// assets-src/MANIFEST.md: the audio rows of the asset table and the totals line
const mdPath = path.join(ROOT, 'assets-src/MANIFEST.md');
let md = fs.readFileSync(mdPath, 'utf8');
const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
for (const r of records) {
  const title = r.title + (r.note ? ` [${r.note}]` : '');
  const row = `| \`${r.path}\` | ${esc(title)} | ${esc(r.author)} | ${esc(r.source_page)} | ${esc(r.download_url)} | ${esc(r.license)} | ${esc(r.processing)} |`;
  const re = new RegExp(`^\\| \`${r.path.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\` \\|.*$`, 'm');
  if (!re.test(md)) throw new Error(`MANIFEST.md has no row for ${r.path}`);
  md = md.replace(re, () => row);
}
const nAudio = records.length, mb = (man.total_bytes / 1e6).toFixed(2);
md = md.replace(/^Totals: .*$/m, (l) => l.replace(/\d+ audio files, \*\*[\d.]+ MB\*\*/, `${nAudio} audio files, **${mb} MB**`));
fs.writeFileSync(mdPath, md);
console.log(`records ${records.length}, original ${records.filter((r) => r.provenance === 'original').length}, total audio bytes ${records.reduce((s, r) => s + r.bytes, 0)}, manifest total ${man.total_bytes}`);
